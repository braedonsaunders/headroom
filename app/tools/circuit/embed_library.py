#!/usr/bin/env python3
"""Regenerates src/circuit/library/EmbeddedLibrary.hpp from src/circuit/library/*.circuit.json.

The JSON netlists are the source of truth; the header only lets the engine (and the DAW plug-in, which has no
resource bundle) carry them. test_circuit_engine fails if the two drift apart.
Usage: python3 tools/circuit/embed_library.py
"""
import json, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
lib = root / "src" / "circuit" / "library"
out = lib / "EmbeddedLibrary.hpp"
entries = []
for f in sorted(lib.glob("*.circuit.json")):
    text = f.read_text(encoding="utf-8")
    cid = json.loads(text)["id"]
    chunks = [text[i:i + 6000] for i in range(0, len(text), 6000)]
    lit = "\n".join(f'R"hrjson({c})hrjson"' for c in chunks)
    entries.append(f'    {{"{cid}", "{f.name}",\n{lit}}},')
blocks = []
for f in sorted(lib.glob("*.blocks.json")):
    text = f.read_text(encoding="utf-8")
    json.loads(text)
    chunks = [text[i:i + 6000] for i in range(0, len(text), 6000)]
    lit = "\n".join(f'R"hrjson({c})hrjson"' for c in chunks)
    blocks.append(f'    {{"{f.name}",\n{lit}}},')
out.write_text(
    "#pragma once\n"
    "// GENERATED by tools/circuit/embed_library.py from src/circuit/library/*.circuit.json. Do not edit.\n"
    "namespace rig::ce::library {\n"
    "struct Embedded {\n    const char* id;\n    const char* file;\n    const char* json;\n};\n"
    "inline constexpr Embedded kEmbedded[] = {\n" + "\n".join(entries) + "\n};\n"
    "struct EmbeddedBlocks {\n    const char* file;\n    const char* json;\n};\n"
    "inline constexpr EmbeddedBlocks kBlocks[] = {\n" + "\n".join(blocks) + "\n};\n"
    "} // namespace rig::ce::library\n", encoding="utf-8")
print(f"wrote {out} ({len(entries)} circuits)")
